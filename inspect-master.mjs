import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createSign } from 'node:crypto';
const keyPath = process.argv[2];
const key = JSON.parse(await readFile(keyPath, 'utf8'));
if (key.type !== 'service_account' || !key.private_key || !key.client_email) throw new Error('Invalid service account file');
const encode = value => Buffer.from(JSON.stringify(value)).toString('base64url');
const now = Math.floor(Date.now()/1000);
const input = encode({alg:'RS256',typ:'JWT'})+'.'+encode({iss:key.client_email,scope:'https://www.googleapis.com/auth/drive',aud:'https://oauth2.googleapis.com/token',iat:now,exp:now+3600});
const signer = createSign('RSA-SHA256'); signer.update(input);
const assertion = input+'.'+signer.sign(key.private_key).toString('base64url');
const tokenResponse = await fetch('https://oauth2.googleapis.com/token',{method:'POST',body:new URLSearchParams({grant_type:'urn:ietf:params:oauth:grant-type:jwt-bearer',assertion})});
const tokenBody = await tokenResponse.json();
if (!tokenResponse.ok) throw new Error('Service account authentication failed: '+tokenResponse.status);
const headers = {Authorization:'Bearer '+tokenBody.access_token};
const id = '1j3c-5P4CMd0kktcA-aGqZWb-XZHY3cO8';
const metadataResponse = await fetch('https://www.googleapis.com/drive/v3/files/'+id+'?fields=id,name,mimeType,size,version,modifiedTime,headRevisionId,capabilities(canEdit)',{headers});
if (!metadataResponse.ok) {
  const failure = await metadataResponse.json();
  console.log(JSON.stringify({authenticated:true,status:metadataResponse.status,error:failure.error?.message,reasons:failure.error?.errors?.map(e=>e.reason),details:failure.error?.details?.map(d=>({reason:d.reason,service:d.metadata?.service,activationUrl:d.metadata?.activationUrl}))}));
  process.exit(1);
}
const metadata = await metadataResponse.json();
console.log(JSON.stringify({authenticated:true,master:metadata}));
if (!metadata.capabilities?.canEdit) throw new Error('Service account cannot edit Master');
await mkdir('.local',{recursive:true});
await writeFile('.local/master-metadata.json',JSON.stringify(metadata));
const response = await fetch('https://www.googleapis.com/drive/v3/files/'+id+'?alt=media',{headers});
if (!response.ok) throw new Error('Master download failed: '+response.status);
await writeFile('.local/master-before.xlsx',Buffer.from(await response.arrayBuffer()));
console.log('Master downloaded for read-only inspection.');
const origin = 'https://spine-preparation.manoosaki65.workers.dev';
const records = await fetch(origin+'/api/spine-records');
if (!records.ok) throw new Error('Site records inspection failed: '+records.status);
const recordsText = await records.text();
await writeFile('.local/site-records-before.json',recordsText);
const page = await fetch(origin+'/spine/');
const html = await page.text();
await writeFile('.local/site-before.html',html);
console.log(JSON.stringify({siteRecords:JSON.parse(recordsText).items.length,pageStatus:page.status,scripts:[...html.matchAll(/<script[^>]*src=["']([^"']+)/g)].map(m=>m[1])}));
